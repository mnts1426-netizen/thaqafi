// يحدد فئة كل فريق في المباراة الواحدة: win (الصدارة المنفردة) / loss (الأخير المنفرد) / draw (الوسط وأي تعادل).
// التعادل في أي مركز يأخذ نقاط التعادل نفسها، تماماً كما كان بين فريقين. place: ترتيب تنافسي (المتعادلان يشتركان في المركز).
function computeMatchTiers(scores) {
  const sorted = scores.slice().sort((a, b) => b.score - a.score);
  const top = sorted[0].score;
  const bottom = sorted[sorted.length - 1].score;
  const countAt = (v) => sorted.filter((s) => s.score === v).length;
  return sorted.map((s) => {
    const place = sorted.findIndex((x) => x.score === s.score) + 1;
    let tier = "draw";
    if (top !== bottom) {
      if (s.score === top && countAt(top) === 1) tier = "win";
      else if (s.score === bottom && countAt(bottom) === 1) tier = "loss";
    }
    return { ...s, place, tier, tied: countAt(s.score) > 1 };
  });
}

// نقاط الدوري لفئة المباراة (الخسارة: نقطة إن سجّل الفريق هدفاً، وإلا صفر)
function leaguePointsFor(tier, score) {
  if (tier === "win") return CONFIG.matchPoints.win;
  if (tier === "draw") return CONFIG.matchPoints.drawEach;
  return score > 0 ? CONFIG.matchPoints.lossIfScored : CONFIG.matchPoints.lossIfZero;
}
